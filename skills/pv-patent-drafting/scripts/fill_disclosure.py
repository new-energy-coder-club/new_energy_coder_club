# ===== 后处理：将图片由“嵌入型”转换为“上下型环绕”（wp:anchor + wrapTopAndBottom） =====
import zipfile, shutil, re as _re

def inline_to_anchor(docxml):
    def repl(m):
        attrs, inner = m.group(1), m.group(2)
        extent = _re.search(r'<wp:extent[^>]*/>', inner).group(0)
        docpr = _re.search(r'<wp:docPr[^>]*/>', inner).group(0)
        locks = _re.search(r'<wp:cNvGraphicFramePr>.*?</wp:cNvGraphicFramePr>', inner, _re.S).group(0)
        graphic = _re.search(r'<a:graphic>.*?</a:graphic>', inner, _re.S).group(0)
        return ('<w:drawing><wp:anchor distT="0" distB="0" distL="0" distR="0" simplePos="0" '
                'relativeHeight="0" behindDoc="0" locked="0" layoutInCell="1" allowOverlap="1">'
                '<wp:simplePos x="0" y="0"/>'
                '<wp:positionH relativeFrom="column"><wp:align>center</wp:align></wp:positionH>'
                '<wp:positionV relativeFrom="paragraph"><wp:posOffset>0</wp:posOffset></wp:positionV>'
                + extent +
                '<wp:effectExtent l="0" t="0" r="0" b="0"/>'
                '<wp:wrapTopAndBottom/>'
                + docpr + locks + graphic +
                '</wp:anchor></w:drawing>')
    return _re.sub(r'<w:drawing><wp:inline([^>]*)>(.*?)</wp:inline></w:drawing>', repl, docxml, flags=_re.S)

tmp = OUT + '.tmp'
with zipfile.ZipFile(OUT, 'r') as zin, zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as zout:
    for item in zin.namelist():
        data = zin.read(item)
        if item == 'word/document.xml':
            xml = data.decode('utf-8')
            n = xml.count('<wp:inline')
            xml = inline_to_anchor(xml)
            print('inline->anchor converted:', n)
            data = xml.encode('utf-8')
        zout.writestr(item, data)
shutil.move(tmp, OUT)
print('anchor post-process done')
