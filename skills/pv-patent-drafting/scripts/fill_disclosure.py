def main():
    session = WIRSession.open(SRC)
    w, wir, _ = session.read(part='document')

    edits = []
    for key, text in EDITS:
        m = re.search(r'<p k="%s" class="[^"]*">\s*<r class="([^"]*)">.*?</r>\s*</p>' % key, wir, re.S)
        if not m:
            print('!! not found:', key)
            continue
        old = m.group(0)
        runcls = m.group(1)
        ptag = old[:old.index('>')+1]
        new = '%s<r class="%s">%s</r></p>' % (ptag, runcls, esc(text))
        edits.append(TextEdit(old_string=old, new_string=new))

    print('prepared text edits:', len(edits))
    # 分批执行（每批3个）
    for i in range(0, len(edits), 3):
        batch = edits[i:i+3]
        session.edit(w, batch)
        if session.last_edit_warnings:
            print('warnings:', session.last_edit_warnings)

    # 重新读取，处理图片
